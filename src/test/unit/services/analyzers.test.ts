import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { analyzerAssemblies, generatedFiles, parseAnalyzerQuery, sourceGenerators } from '../../../services/analyzers';

describe('analyzers', () => {
    const msbuildOutput = JSON.stringify({
        Properties: { CompilerGeneratedFilesOutputPath: 'obj/Debug/net10.0//generated' },
        Items: {
            Analyzer: [
                { Identity: '/sdk/analyzers/cs/Microsoft.AspNetCore.Analyzers.dll', FullPath: '/sdk/analyzers/cs/Microsoft.AspNetCore.Analyzers.dll' },
                { Identity: '/packs/analyzers/dotnet/cs/System.Text.Json.SourceGeneration.dll', FullPath: '/packs/analyzers/dotnet/cs/System.Text.Json.SourceGeneration.dll' },
                // The same analyzer from another pack
                { Identity: '/other/System.Text.Json.SourceGeneration.dll', FullPath: '/other/System.Text.Json.SourceGeneration.dll' },
            ],
        },
    });

    it('reads the analyzer assemblies and the generated files folder from MSBuild', () => {
        expect(parseAnalyzerQuery(msbuildOutput, '/repo/Web')).toEqual({
            generatedDir: path.join('/repo/Web', 'obj', 'Debug', 'net10.0', 'generated'),
            analyzers: ['Microsoft.AspNetCore.Analyzers', 'System.Text.Json.SourceGeneration'],
        });
    });

    it('copes with projects without analyzers', () => {
        expect(parseAnalyzerQuery(JSON.stringify({ Properties: { CompilerGeneratedFilesOutputPath: '' }, Items: {} }), '/repo/Lib'))
            .toEqual({ generatedDir: undefined, analyzers: [] });
    });

    describe('generated files', () => {
        let generatedDir: string;

        beforeEach(() => {
            generatedDir = fs.mkdtempSync(path.join(os.tmpdir(), 'generated-'));
            const write = (relative: string) => {
                const file = path.join(generatedDir, relative);
                fs.mkdirSync(path.dirname(file), { recursive: true });
                fs.writeFileSync(file, '// <auto-generated/>');
            };
            write('Microsoft.CodeAnalysis.Razor.Compiler/Microsoft.NET.Sdk.Razor.SourceGenerators.RazorSourceGenerator/Pages_Privacy_cshtml.g.cs');
            write('Microsoft.CodeAnalysis.Razor.Compiler/Microsoft.NET.Sdk.Razor.SourceGenerators.RazorSourceGenerator/Pages_Index_cshtml.g.cs');
            write('System.Text.Json.SourceGeneration/System.Text.Json.SourceGeneration.JsonSourceGenerator/Models/Context.g.cs');
        });

        afterEach(() => fs.rmSync(generatedDir, { recursive: true, force: true }));

        it('lists the analyzers, with generators that only show up through their output (Razor)', () => {
            const { analyzers } = parseAnalyzerQuery(msbuildOutput, '/repo/Web');
            expect(analyzerAssemblies(analyzers, generatedDir)).toEqual([
                { name: 'Microsoft.AspNetCore.Analyzers', hasGenerated: false },
                { name: 'Microsoft.CodeAnalysis.Razor.Compiler', hasGenerated: true },
                { name: 'System.Text.Json.SourceGeneration', hasGenerated: true },
            ]);
        });

        it('lists the generators of an analyzer and the files each generated', () => {
            expect(sourceGenerators(generatedDir, 'Microsoft.CodeAnalysis.Razor.Compiler'))
                .toEqual(['Microsoft.NET.Sdk.Razor.SourceGenerators.RazorSourceGenerator']);
            expect(generatedFiles(generatedDir, 'Microsoft.CodeAnalysis.Razor.Compiler', 'Microsoft.NET.Sdk.Razor.SourceGenerators.RazorSourceGenerator')
                .map(file => path.basename(file))).toEqual(['Pages_Index_cshtml.g.cs', 'Pages_Privacy_cshtml.g.cs']);
            expect(generatedFiles(generatedDir, 'System.Text.Json.SourceGeneration', 'System.Text.Json.SourceGeneration.JsonSourceGenerator'))
                .toEqual([path.join(generatedDir, 'System.Text.Json.SourceGeneration', 'System.Text.Json.SourceGeneration.JsonSourceGenerator', 'Models', 'Context.g.cs')]);
        });

        it('has nothing before the first build', () => {
            const missing = path.join(generatedDir, 'missing');
            expect(analyzerAssemblies(['Microsoft.AspNetCore.Analyzers'], missing)).toEqual([{ name: 'Microsoft.AspNetCore.Analyzers', hasGenerated: false }]);
            expect(sourceGenerators(missing, 'Microsoft.AspNetCore.Analyzers')).toEqual([]);
        });
    });
});
